package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// inTempModule lays out a module (go.mod + files) in a temp directory and
// makes it the working directory: run/subpackages operate on "." and the
// nearest go.mod, so the tests exercise the tool as go:generate invokes it.
// Tests are not parallel — the working directory is process-wide.
func inTempModule(t *testing.T, files map[string]string) {
	t.Helper()
	tmp := t.TempDir()
	for path, content := range files {
		p := filepath.Join(tmp, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatalf("mkdir %s: %v", path, err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", path, err)
		}
	}
	old, err := os.Getwd()
	if err != nil {
		t.Fatalf("getwd: %v", err)
	}
	if err := os.Chdir(tmp); err != nil {
		t.Fatalf("chdir: %v", err)
	}
	t.Cleanup(func() { os.Chdir(old) })
}

func TestRenderNoSubpackages(t *testing.T) {
	got := render("flowdeck", nil)
	want := "package workflows\n"
	if strings.Contains(got, "import (") || !strings.HasSuffix(got, want) {
		t.Fatalf("render(nil):\n%s", got)
	}
	if !strings.Contains(got, "Code generated by workflowgen; DO NOT EDIT.") {
		t.Fatalf("missing generated header:\n%s", got)
	}
}

func TestRenderWithSubpackages(t *testing.T) {
	got := render("flowdeck", []string{"buy", "ship/express"})
	for _, want := range []string{
		"\t_ \"flowdeck/workflows/buy\"\n",
		"\t_ \"flowdeck/workflows/ship/express\"\n",
		"import (",
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("render missing %q:\n%s", want, got)
		}
	}
}

func TestSubpackages(t *testing.T) {
	inTempModule(t, map[string]string{
		"go.mod":                  "module flowdeck\n",
		"workflows.go":            "package workflows\n",
		"zz_generated.go":         "package workflows\n",
		"buy/buy.go":              "package buy\n",
		"buy/buy_test.go":         "package buy\n",
		"ship/express/express.go": "package express\n",
		"emptydir/README.md":      "no go files here\n",
		"testonly/only_test.go":   "package testonly\n",
	})
	pkgs, err := subpackages(".")
	if err != nil {
		t.Fatalf("subpackages: %v", err)
	}
	if strings.Join(pkgs, ",") != "buy,ship/express" {
		t.Fatalf("subpackages: got %v", pkgs)
	}
}

func TestModuleName(t *testing.T) {
	inTempModule(t, map[string]string{"go.mod": "module flowdeck_test\ngo 1.25\n"})
	name, err := moduleName()
	if err != nil {
		t.Fatalf("moduleName: %v", err)
	}
	if name != "flowdeck_test" {
		t.Fatalf("moduleName: got %q", name)
	}
}

func TestModuleLineMissing(t *testing.T) {
	if _, err := moduleLine("go 1.25\n", "d"); err == nil {
		t.Fatal("moduleLine without a module line: want error")
	}
}

func TestRunWritesGeneratedFile(t *testing.T) {
	inTempModule(t, map[string]string{
		"go.mod":     "module flowdeck\n",
		"buy/buy.go": "package buy\n",
	})
	if err := run(); err != nil {
		t.Fatalf("run: %v", err)
	}
	data, err := os.ReadFile("zz_generated.go")
	if err != nil {
		t.Fatalf("read generated file: %v", err)
	}
	if want := "\t_ \"flowdeck/workflows/buy\"\n"; !strings.Contains(string(data), want) {
		t.Fatalf("generated file missing %q:\n%s", want, data)
	}
}
