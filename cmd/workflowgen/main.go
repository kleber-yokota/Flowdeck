// Command workflowgen writes workflows/zz_generated.go: the RegisterAll
// call list — one generated call per workflow subpackage — so main.go
// keeps a single registration call and a new workflow folder is wired by
// regeneration, not by editing.
//
// It runs with the workflows/ directory as its working directory:
//
//	go generate ./workflows
//
// (the //go:generate directive lives in workflows/workflows.go).
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "workflowgen:", err)
		os.Exit(1)
	}
}

func run() error {
	modName, err := moduleName()
	if err != nil {
		return err
	}
	pkgs, err := subpackages(".")
	if err != nil {
		return err
	}
	return os.WriteFile("zz_generated.go", []byte(render(modName, pkgs)), 0o644)
}

// render builds the source of zz_generated.go: the package clause plus
// the RegisterAll call list (empty subpackage list: the package clause
// only).
func render(modName string, pkgs []string) string {
	var b strings.Builder
	b.WriteString("// Code generated by workflowgen; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// RegisterAll registers every workflow subpackage on the\n")
	b.WriteString("// core DBOS context — one generated call per subpackage.\n")
	b.WriteString("// Regenerate after adding a subpackage: go generate ./workflows\n")
	b.WriteString("package workflows\n")
	if len(pkgs) > 0 {
		b.WriteString("\nimport (\n")
		b.WriteString("\t\"github.com/dbos-inc/dbos-transact-golang/dbos\"\n")
		b.WriteString("\n")
		for _, p := range pkgs {
			fmt.Fprintf(&b, "\t%q\n", modName+"/workflows/"+p)
		}
		b.WriteString(")\n")
		b.WriteString("\n// RegisterAll registers every workflow subpackage on the core\n// DBOS context — one call per subpackage, alphabetical.\n")
		b.WriteString("func RegisterAll(c dbos.Context) {\n")
		for _, p := range pkgs {
			fmt.Fprintf(&b, "\t%s.Register(c)\n", packageOf(p))
		}
		b.WriteString("}\n")
	}
	return b.String()
}

// packageOf is the identifier of a subpackage path: its last segment
// (the uniform recipe — the directory name is the package name).
func packageOf(p string) string {
	if i := strings.LastIndex(p, "/"); i >= 0 {
		return p[i+1:]
	}
	return p
}

// moduleName walks up from the current directory to the module root
// (the nearest go.mod) and returns its module name.
func moduleName() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err == nil {
			return moduleLine(string(data), dir)
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod found above %s", dir)
		}
		dir = parent
	}
}

// moduleLine extracts the "module" line from go.mod source.
func moduleLine(src, dir string) (string, error) {
	for _, line := range strings.Split(src, "\n") {
		name := strings.TrimSpace(strings.TrimPrefix(line, "module "))
		if name != line && name != "" {
			return name, nil
		}
	}
	return "", fmt.Errorf("%s/go.mod has no module line", dir)
}

// subpackages returns the relative paths of the subpackages that define
// func Register(c dbos.Context) — the registration the generated
// RegisterAll calls (the steps helper defines no Register and is
// excluded; a test-only directory is not importable, so it is skipped).
func subpackages(root string) ([]string, error) {
	files, err := goFiles(root)
	if err != nil {
		return nil, err
	}
	defines := map[string]bool{}
	for _, p := range files {
		ok, perr := hasRegister(p)
		if perr != nil {
			return nil, perr
		}
		if ok {
			defines[filepath.ToSlash(filepath.Dir(p))] = true
		}
	}
	out := []string{}
	for dir := range defines {
		if dir != "." {
			out = append(out, dir)
		}
	}
	sort.Strings(out)
	return out, nil
}

// goFiles walks the tree under root and returns the non-test Go files.
func goFiles(root string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() && isGoFile(d.Name()) {
			out = append(out, p)
		}
		return err
	})
	return out, err
}

// hasRegister reports whether the file declares func Register(c dbos.Context).
func hasRegister(path string) (bool, error) {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return false, fmt.Errorf("parse %s: %w", path, err)
	}
	for _, decl := range f.Decls {
		if registerDecl(decl) {
			return true, nil
		}
	}
	return false, nil
}

// registerDecl reports whether the declaration is
// func Register(c dbos.Context) — the registration the generated
// RegisterAll calls.
func registerDecl(decl ast.Decl) bool {
	fd, ok := decl.(*ast.FuncDecl)
	if !ok {
		return false
	}
	if fd.Recv != nil || fd.Name.Name != "Register" {
		return false
	}
	if fd.Type.Results != nil {
		return false
	}
	if len(fd.Type.Params.List) != 1 {
		return false
	}
	param := fd.Type.Params.List[0]
	if len(param.Names) != 1 || param.Names[0].Name != "c" {
		return false
	}
	return dbosContext(param.Type)
}

// dbosContext reports whether the expression is the selector dbos.Context.
func dbosContext(expr ast.Expr) bool {
	sel, ok := expr.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	qual, ok := sel.X.(*ast.Ident)
	return ok && qual.Name == "dbos" && sel.Sel.Name == "Context"
}

func isGoFile(name string) bool {
	return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go")
}
